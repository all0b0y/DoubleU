-- 105: dynamic MCP toolsets (#7), HTTP/SSE only.
--
-- Per-tenant MCP servers and a per-role allow-list of the tools a role may call.
-- The draft agent resolves a role's enabled servers (filtered to allowed_tools)
-- at request time. Everything is opt-in: no rows => no MCP, unchanged behaviour.
CREATE TABLE IF NOT EXISTS public.mcp_servers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id text NOT NULL,
    name text NOT NULL,
    transport text NOT NULL,
    url text NOT NULL,
    -- Optional Authorization header value, passed to the AI service over the
    -- internal Go->Python channel (plaintext, same trust model as bot tokens).
    auth_header text,
    enabled boolean NOT NULL DEFAULT true,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT mcp_servers_transport_check CHECK (transport = ANY (ARRAY['http'::text, 'sse'::text])),
    CONSTRAINT mcp_servers_tenant_name_key UNIQUE (tenant_id, name)
);

CREATE INDEX IF NOT EXISTS idx_mcp_servers_tenant ON public.mcp_servers USING btree (tenant_id) WHERE enabled;

-- Role -> server access. allowed_tools NULL = every tool the server exposes;
-- a non-null array = only those tool names (deny-by-default for the rest).
CREATE TABLE IF NOT EXISTS public.role_mcp_access (
    role_id bigint NOT NULL REFERENCES public.ai_roles(id) ON DELETE CASCADE,
    mcp_server_id bigint NOT NULL REFERENCES public.mcp_servers(id) ON DELETE CASCADE,
    allowed_tools text[],
    PRIMARY KEY (role_id, mcp_server_id)
);
