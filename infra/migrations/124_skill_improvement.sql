-- 124: skill self-improvement foundation — usage telemetry, versioning, toggle.
-- Signal (which skill was loaded, and whether the owner liked the resulting
-- reply) drives an owner-triggered "improve skill" pass; every body change is
-- versioned so a curated edit is always revertible.

-- One row per load_skill call. rating is filled in post-hoc from owner draft
-- feedback on the turn that loaded the skill (up|down), NULL until then.
CREATE TABLE IF NOT EXISTS public.skill_usage (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id text NOT NULL,
    skill_id bigint NOT NULL REFERENCES public.skills(id) ON DELETE CASCADE,
    chat_id text NOT NULL,
    source_message_id text NOT NULL DEFAULT '',
    rating text CHECK (rating IN ('up', 'down')),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_skill_usage_skill ON public.skill_usage (skill_id);
CREATE INDEX IF NOT EXISTS idx_skill_usage_turn
    ON public.skill_usage (tenant_id, chat_id, source_message_id);

-- Immutable snapshot of a skill body at each change, so owner/curator edits can
-- be rolled back. author records who produced the version.
CREATE TABLE IF NOT EXISTS public.skill_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id bigint NOT NULL REFERENCES public.skills(id) ON DELETE CASCADE,
    body text NOT NULL,
    content_hash text NOT NULL DEFAULT '',
    author text NOT NULL DEFAULT 'owner' CHECK (author IN ('owner', 'curator')),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_skill_versions_skill
    ON public.skill_versions (skill_id, created_at DESC);

-- Per-role opt-in for the autonomous curator (increment 1b). Off by default:
-- increment 1 is owner-triggered only.
ALTER TABLE public.ai_roles
    ADD COLUMN IF NOT EXISTS auto_improve_skills boolean NOT NULL DEFAULT false;
