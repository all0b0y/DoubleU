#!/usr/bin/env python3
"""Generate Go and Python enum definitions from contracts/contracts.json.

This script is the only writer for two files:

  - backend-go/internal/contracts/contract_enums.gen.go
  - ai-python/ai_agent/contract_enums.py

`contracts/contracts.json` is the single source of truth for cross-service
enum values, confidence thresholds, and risk policy.  Hand-editing the
generated files is forbidden — re-run this script instead.

Invocation:
    python3 scripts/generate_contracts.py

CI tip: run the script and `git diff --exit-code` on the generated paths;
non-empty diff means someone changed an enum without re-generating.
"""

from __future__ import annotations

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONTRACTS_JSON = ROOT / "contracts" / "contracts.json"
GO_OUT = ROOT / "backend-go" / "internal" / "contracts" / "contract_enums.gen.go"
PY_OUT = ROOT / "ai-python" / "ai_agent" / "contract_enums.py"

# Map JSON enum keys to the Go type name they live under.  The type is still
# declared (with its IsValid method) in types.go; this generator only emits the
# value constants and a slice listing every legal value.
GO_ENUM_TYPES: dict[str, dict[str, str]] = {
    "decisions":        {"type": "Decision",       "const_prefix": "Decision"},
    "chat_modes":       {"type": "ChatMode",       "const_prefix": "ChatMode"},
    "privacy_flags":    {"type": "PrivacyFlag",    "const_prefix": "Privacy"},
    "risk_levels":      {"type": "RiskLevel",      "const_prefix": "Risk"},
    "approval_actions": {"type": "ApprovalAction", "const_prefix": "Approval"},
    "message_states":   {"type": "MessageState",   "const_prefix": "State"},
    "llm_purposes":     {"type": "LLMPurpose",     "const_prefix": "Purpose"},
}

# Map JSON enum keys to the Python Enum class name.
PY_ENUM_TYPES: dict[str, str] = {
    "decisions":        "Decision",
    "chat_modes":       "ChatMode",
    "privacy_flags":    "PrivacyFlag",
    "risk_levels":      "RiskLevel",
    "approval_actions": "ApprovalAction",
    "message_states":   "MessageState",
    "llm_purposes":     "LLMPurpose",
}


# Initialisms preserved as ALL-CAPS in Go identifiers, per the existing
# codebase convention (Go style guide rule: initialisms keep their case).
GO_INITIALISMS = {"ai", "id", "url", "ip", "http", "api", "json", "sql", "xml"}


def to_pascal_case(value: str) -> str:
    """Convert "auto_reply" -> "AutoReply", "ai_refine" -> "AIRefine"."""
    parts = value.split("_")
    out: list[str] = []
    for part in parts:
        if part in GO_INITIALISMS:
            out.append(part.upper())
        else:
            out.append(part.capitalize())
    return "".join(out)


def to_screaming_snake(value: str) -> str:
    """Convert "auto_reply" -> "AUTO_REPLY"."""
    return value.upper()


def render_go(data: dict) -> str:
    """Render contract_enums.gen.go."""
    lines: list[str] = [
        "// Code generated by scripts/generate_contracts.py. DO NOT EDIT.",
        "//",
        "// Source of truth: contracts/contracts.json",
        "//",
        "// The corresponding Go types (Decision, ChatMode, …) are declared in",
        "// types.go together with their IsValid methods.  This file only carries",
        "// the value constants and per-enum All* slices so drift between Go,",
        "// Python, and the JSON contract is impossible.",
        "",
        "package contracts",
        "",
    ]
    lines.append(f"// ContractVersion is the version of contracts/contracts.json this code was generated from.")
    lines.append(f'const ContractVersion = "{data["version"]}"')
    lines.append("")
    for key, meta in GO_ENUM_TYPES.items():
        type_name = meta["type"]
        prefix = meta["const_prefix"]
        values: list[str] = data[key]
        lines.append(f"// {type_name} values from the frozen contract.")
        lines.append("const (")
        for v in values:
            const_name = f"{prefix}{to_pascal_case(v)}"
            lines.append(f'\t{const_name} {type_name} = "{v}"')
        lines.append(")")
        lines.append("")
        all_name = f"All{to_pascal_case(key)}"
        lines.append(f"// {all_name} lists every legal {type_name} value.")
        lines.append(f"var {all_name} = []{type_name}{{")
        for v in values:
            const_name = f"{prefix}{to_pascal_case(v)}"
            lines.append(f"\t{const_name},")
        lines.append("}")
        lines.append("")
    # Confidence thresholds.
    thresholds = data["confidence_thresholds"]
    lines.append("// Confidence thresholds from the contract.")
    lines.append("const (")
    lines.append(f'\t// SemiAutoMinConfidence is the minimum confidence for semi-auto replies.')
    lines.append(f'\tSemiAutoMinConfidence = {thresholds["semi_auto_min"]}')
    lines.append(f'\t// AutoMinConfidence is the minimum confidence for auto replies.')
    lines.append(f'\tAutoMinConfidence = {thresholds["auto_min"]}')
    lines.append(")")
    lines.append("")
    return "\n".join(lines) + "\n"


def render_python(data: dict) -> str:
    """Render contract_enums.py."""
    lines: list[str] = [
        '"""Generated cross-service contract enums.',
        "",
        "Source of truth: contracts/contracts.json.",
        "Regenerate via scripts/generate_contracts.py — do not edit this file by hand.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from enum import Enum",
        "",
        f'CONTRACT_VERSION = "{data["version"]}"',
        "",
    ]
    for key, class_name in PY_ENUM_TYPES.items():
        values: list[str] = data[key]
        lines.append(f"class {class_name}(str, Enum):")
        lines.append(f'    """Generated from contracts.json {key!r}."""')
        for v in values:
            lines.append(f'    {to_screaming_snake(v)} = "{v}"')
        lines.append("")
    thresholds = data["confidence_thresholds"]
    lines.append("# Confidence thresholds from the contract.")
    lines.append(f'SEMI_AUTO_MIN_CONFIDENCE = {thresholds["semi_auto_min"]}')
    lines.append(f'AUTO_MIN_CONFIDENCE = {thresholds["auto_min"]}')
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    data = json.loads(CONTRACTS_JSON.read_text())
    # Sanity: every JSON enum key must be wired into both generators.
    json_enum_keys = {
        k for k, v in data.items()
        if isinstance(v, list) and k in GO_ENUM_TYPES
    }
    if json_enum_keys != set(GO_ENUM_TYPES):
        sys.stderr.write(
            f"contracts.json enum keys {json_enum_keys} do not match generator map "
            f"{set(GO_ENUM_TYPES)}\n"
        )
        return 1
    GO_OUT.write_text(render_go(data))
    PY_OUT.write_text(render_python(data))
    print(f"wrote {GO_OUT.relative_to(ROOT)}")
    print(f"wrote {PY_OUT.relative_to(ROOT)}")
    # Strip trailing whitespace just in case.
    for p in (GO_OUT, PY_OUT):
        cleaned = re.sub(r"[ \t]+\n", "\n", p.read_text())
        p.write_text(cleaned)
    return 0


if __name__ == "__main__":
    sys.exit(main())
